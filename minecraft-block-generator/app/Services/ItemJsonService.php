<?php

namespace App\Services;

class ItemJsonService
{
    use PackManifests;

    public function itemBehavior(
        string $identifier,
        ?int $maxStackSize = null,
        ?int $maxDurability = null,
        ?int $itemTier = null,
        ?float $itemMultiplier = null,
        ?int $damage = null,
        ?bool $handEquipped = null,
    ): array {
        $components = [
            'minecraft:display_name' => [
                'value' => '§r' . $identifier,
            ],
        ];

        if ($maxStackSize !== null) {
            $components['minecraft:max_stack_size'] = ['value' => $maxStackSize];
        }

        if ($maxDurability !== null) {
            $components['minecraft:durability'] = ['max_durability' => $maxDurability];
        }

        if ($itemTier !== null && $itemMultiplier !== null) {
            $components['minecraft:axe'] = [
                'tier' => $itemTier,
                'multiplier' => $itemMultiplier,
            ];
        }

        if ($damage !== null && $damage > 0) {
            $components['minecraft:damage'] = ['damage' => $damage];
        }

        if ($handEquipped === true) {
            $components['minecraft:hand_equipped'] = ['enabled' => true];
        }

        return [
            'format_version' => '1.16.100',
            'minecraft:item' => [
                'description' => [
                    'identifier' => 'custom:' . $identifier,
                    'category'   => 'equipment',
                ],
                'components' => $components,
            ],
        ];
    }

    public function itemTexture(string $identifier): array
    {
        return [
            'resource_pack_name' => 'custom_items',
            'texture_name'       => 'atlas.items',
            'texture_data'       => [
                'custom:' . $identifier => [
                    'textures' => 'textures/items/' . $identifier,
                ],
            ],
        ];
    }

    public function itemsJson(string $identifier): array
    {
        return [
            'format_version' => '1.21.40',
            'custom:' . $identifier => [
                'textures' => 'custom:' . $identifier,
            ],
        ];
    }

    public function languagesJson(): array
    {
        return ['en_US'];
    }

    public function textsLang(string $identifier, string $name): string
    {
        return "pack.name=Custom Items Resource Pack\npack.description=Generated by Minecraft Block Generator\nitem.custom:{$identifier}.name={$name}\n";
    }
}
